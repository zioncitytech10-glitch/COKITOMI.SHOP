-- COKITOMI initial database schema
-- Run this entire file in Supabase Dashboard > SQL Editor > New query.
-- Public storefront visitors can read active products only.
-- Customer order creation will be added through a trusted server/Edge Function
-- after payment verification; never allow browser clients to mark orders paid.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  supplier varchar(40),
  supplier_product_id text unique,
  slug text not null unique,
  name text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  currency char(3) not null default 'USD',
  image_url text,
  gallery_urls text[] not null default '{}',
  stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  order_number text not null unique,
  email text not null,
  status text not null default 'pending'
    check (status in ('pending','payment_processing','paid','submitted_to_supplier','processing','shipped','delivered','cancelled','refunded','fulfillment_error')),
  currency char(3) not null default 'USD',
  subtotal numeric(10,2) not null check (subtotal >= 0),
  shipping_total numeric(10,2) not null default 0 check (shipping_total >= 0),
  tax_total numeric(10,2) not null default 0 check (tax_total >= 0),
  total numeric(10,2) not null check (total >= 0),
  shipping_name text,
  shipping_address jsonb not null default '{}'::jsonb,
  payment_provider text,
  payment_reference text unique,
  supplier_order_id text,
  tracking_number text,
  tracking_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  supplier_product_id text,
  variant_id text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(10,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists products_active_idx on public.products (is_active);
create index if not exists orders_user_id_idx on public.orders (user_id);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists order_items_order_id_idx on public.order_items (order_id);

alter table public.products enable row level security;
alter table public.customer_profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Remove/recreate named policies safely if this script is run again.
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select
  to anon, authenticated
  using (is_active = true);

-- Table privileges are separate from RLS policies. This grants read access to
-- the public catalogue while the policy above still limits rows to active items.
grant select on table public.products to anon, authenticated;

drop policy if exists "Customers can read own profile" on public.customer_profiles;
create policy "Customers can read own profile"
  on public.customer_profiles for select
  to authenticated
  using (auth.uid() = id);

drop policy if exists "Customers can insert own profile" on public.customer_profiles;
create policy "Customers can insert own profile"
  on public.customer_profiles for insert
  to authenticated
  with check (auth.uid() = id);

drop policy if exists "Customers can update own profile" on public.customer_profiles;
create policy "Customers can update own profile"
  on public.customer_profiles for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

drop policy if exists "Customers can read own orders" on public.orders;
create policy "Customers can read own orders"
  on public.orders for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Customers can read own order items" on public.order_items;
create policy "Customers can read own order items"
  on public.order_items for select
  to authenticated
  using (
    exists (
      select 1 from public.orders
      where orders.id = order_items.order_id
        and orders.user_id = auth.uid()
    )
  );

-- Intentionally no browser INSERT/UPDATE policies for orders, order_items or products.
-- Trusted backend code will create orders only after payment verification and
-- will manage supplier credentials, payment secrets, and fulfilment status.
